/**
 * Resolves a payments key to its localized string with deterministic
 * fallback: target culture → `en` → the key path itself. Never throws.
 */
export function translatePaymentsKey(
  culture: Culture,
  key: string,
  params?: TranslationParams,
): string {
  return translate(PAYMENTS_TRANSLATION_RESOURCES, culture, key, params);
}
