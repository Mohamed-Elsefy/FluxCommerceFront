/** Bundled users dictionaries keyed by supported culture. */
export const USERS_TRANSLATION_RESOURCES: TranslationResources = {
  en: EN_USERS,
  fr: FR_USERS,
  de: DE_USERS,
  es: ES_USERS,
  ar: AR_USERS,
};

/**
 * Resolves a users key to its localized string with deterministic
 * fallback: target culture → `en` → the key path itself. `params` fills
 * `{placeholder}` slots. Never throws.
 */
export function translateUsersKey(
  culture: Culture,
  key: string,
  params: TranslationParams = {},
): string {
  return translate(USERS_TRANSLATION_RESOURCES, culture, key, params);
}
