/** Bundled auth dictionaries keyed by supported culture. */
export const AUTH_TRANSLATION_RESOURCES: TranslationResources = {
  en: EN_AUTH,
  fr: FR_AUTH,
  de: DE_AUTH,
  es: ES_AUTH,
  ar: AR_AUTH,
};

/**
 * Resolves an auth key to its localized string with deterministic
 * fallback: target culture → `en` → the key path itself. `params` fills
 * `{placeholder}` slots (e.g. `{email}`). Never throws.
 */
export function translateAuthKey(
  culture: Culture,
  key: string,
  params: TranslationParams = {},
): string {
  return translate(AUTH_TRANSLATION_RESOURCES, culture, key, params);
}
